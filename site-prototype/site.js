function mountMobileNav(header, index) {
  const nav = header.querySelector(".site-nav");
  const brand = header.querySelector(".brand-block");

  if (!nav || !brand) return;

  const navId = nav.id || `site-nav-${index + 1}`;
  nav.id = navId;

  let button = header.querySelector(".nav-toggle");
  if (!button) {
    button = document.createElement("button");
    button.type = "button";
    button.className = "nav-toggle";
    button.setAttribute("aria-label", "Открыть меню");
    button.setAttribute("aria-expanded", "false");
    button.setAttribute("aria-controls", navId);
    button.innerHTML = `
      <span class="nav-toggle-bar" aria-hidden="true"></span>
      <span class="nav-toggle-bar" aria-hidden="true"></span>
      <span class="nav-toggle-bar" aria-hidden="true"></span>
    `;
    brand.insertAdjacentElement("afterend", button);
  }

  header.classList.add("has-burger-nav");

  function closeMenu() {
    header.classList.remove("is-nav-open");
    button.setAttribute("aria-expanded", "false");
    button.setAttribute("aria-label", "Открыть меню");
  }

  function toggleMenu() {
    const isOpen = header.classList.toggle("is-nav-open");
    button.setAttribute("aria-expanded", String(isOpen));
    button.setAttribute("aria-label", isOpen ? "Закрыть меню" : "Открыть меню");
  }

  button.addEventListener("click", toggleMenu);

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  window.addEventListener("resize", () => {
    if (window.innerWidth > 760) {
      closeMenu();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closeMenu();
    }
  });
}

document.querySelectorAll(".site-header").forEach((header, index) => {
  if (!header.querySelector(".header-search")) {
    header.classList.add("site-header--compact");
  }

  if (!header.querySelector(".header-actions")) {
    header.classList.add("site-header--no-actions");
  }

  mountMobileNav(header, index);
});

function normalizeSearchValue(value) {
  return value
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function scoreSmartSearch(query, route) {
  if (!query) return 0;

  const haystack = normalizeSearchValue(
    [route.label, route.description, ...(route.keywords || [])].join(" ")
  );

  if (haystack.includes(query)) {
    return query.length + 10;
  }

  return (route.keywords || []).reduce((score, keyword) => {
    const normalizedKeyword = normalizeSearchValue(keyword);
    if (query.includes(normalizedKeyword) || normalizedKeyword.includes(query)) {
      return score + Math.max(normalizedKeyword.length, query.length);
    }
    return score;
  }, 0);
}

function findSmartSearchMatches(query) {
  const normalizedQuery = normalizeSearchValue(query);
  if (!normalizedQuery) return smartSearchRoutes.slice(0, 4);

  return smartSearchRoutes
    .map((route) => ({
      route,
      score: scoreSmartSearch(normalizedQuery, route)
    }))
    .filter((entry) => entry.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((entry) => entry.route)
    .slice(0, 4);
}

function mountHeaderSearch(searchRoot) {
  const input = searchRoot.querySelector('input[type="search"]');
  if (!input) return;

  const panel = document.createElement("div");
  panel.className = "search-suggestions";
  panel.setAttribute("hidden", "");
  searchRoot.appendChild(panel);

  function renderSuggestions(query) {
    const matches = findSmartSearchMatches(query);

    if (!matches.length) {
      panel.innerHTML = `
        <div class="search-suggestion search-suggestion-empty">
          <strong>Ничего точного не нашли</strong>
          <span>Откройте помощь с выбором, и мы подскажем нужный раздел.</span>
        </div>
      `;
      panel.removeAttribute("hidden");
      return;
    }

    panel.innerHTML = matches
      .map(
        (match) => `
          <a class="search-suggestion" href="${match.href}">
            <strong>${match.label}</strong>
            <span>${match.description}</span>
          </a>
        `
      )
      .join("");
    panel.removeAttribute("hidden");
  }

  function closePanel() {
    panel.setAttribute("hidden", "");
  }

  input.addEventListener("focus", () => renderSuggestions(input.value));
  input.addEventListener("input", () => renderSuggestions(input.value));

  input.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      closePanel();
      return;
    }

    if (event.key !== "Enter") return;

    event.preventDefault();
    const firstMatch = findSmartSearchMatches(input.value)[0];
    const fallbackHref = "./selection-help.html";
    window.location.href = firstMatch ? firstMatch.href : fallbackHref;
  });

  document.addEventListener("click", (event) => {
    if (!searchRoot.contains(event.target)) {
      closePanel();
    }
  });
}

