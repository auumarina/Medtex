function getCanonicalUrl() {
  if (!siteMeta.siteBaseUrl) return "";

  const pathname = window.location.pathname.split("/").filter(Boolean);
  const lastSegment = pathname[pathname.length - 1] || "index.html";
  const currentFile = lastSegment.includes(".") ? lastSegment : "index.html";
  const normalizedFile = currentFile === "/" ? "index.html" : currentFile;
  const normalizedHref = normalizedFile === "index.html" ? "/" : `/${normalizedFile}`;

  return `${siteMeta.siteBaseUrl.replace(/\/$/, "")}${normalizedHref}`;
}

function ensureMetaTag(attribute, key, content) {
  if (!content) return;

  let tag = document.head.querySelector(`meta[${attribute}="${key}"]`);
  if (!tag) {
    tag = document.createElement("meta");
    tag.setAttribute(attribute, key);
    document.head.appendChild(tag);
  }
  tag.setAttribute("content", content);
}

