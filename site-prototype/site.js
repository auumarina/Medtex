function getCurrentPageName() {
  const pathname = window.location.pathname.split("/").filter(Boolean);
  const lastSegment = pathname[pathname.length - 1];

  if (!lastSegment || !lastSegment.includes(".")) {
    return "index.html";
  }

  return lastSegment;
}

function applyCopyReplacement(entry) {
  const nodes = document.querySelectorAll(entry.selector);
  if (!nodes.length) return;

  const mode = Object.prototype.hasOwnProperty.call(entry, "html") ? "html" : "text";
  const values = entry[mode];

  if (Array.isArray(values)) {
    nodes.forEach((node, index) => {
      if (values[index] == null) return;
      if (mode === "html") {
        node.innerHTML = values[index];
      } else {
        node.textContent = values[index];
      }
    });
    return;
  }

  nodes.forEach((node) => {
    if (mode === "html") {
      node.innerHTML = values;
    } else {
      node.textContent = values;
    }
  });
}

function applyHumanizedCopy() {
  commonCopyOverrides.forEach(applyCopyReplacement);

  const pageName = getCurrentPageName();
  const pageOverride = pageCopyOverrides[pageName];
  if (!pageOverride) return;

  if (pageOverride.title) {
    document.title = pageOverride.title;
  }

  if (pageOverride.description) {
    const descriptionTag = document.querySelector('meta[name="description"]');
    if (descriptionTag) {
      descriptionTag.setAttribute("content", pageOverride.description);
    }
  }

  (pageOverride.replacements || []).forEach(applyCopyReplacement);
}

